#!/usr/bin/env python3
"""Prepare an isolated exact-pin Makepad accessibility source and Cargo patch config.

Never edits the user's Makepad checkout or Cargo git cache. Repeated calls verify
all patched files before reusing the isolated checkout. Configuration patches all
packages at the pin so Desktop's local plugins share one Makepad type identity.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path
import subprocess
import sys

PIN = "4ec079b02bca9747acde3216cfc370cd558e40f4"
SOURCE = "https://github.com/csheargm/makepad.git"
ROOT = Path(__file__).resolve().parents[1]
PATCH = ROOT / "packaging/owner-controller/makepad-accessibility.patch"


def run(args: list[str], cwd: Path | None = None) -> str:
    return subprocess.check_output(args, cwd=cwd, text=True, stderr=subprocess.PIPE).rstrip("\n")


def patched_files(patch: str) -> list[str]:
    return [line.split(" b/", 1)[1] for line in patch.splitlines() if line.startswith("diff --git a/")]


def fingerprints(source: Path, paths: list[str]) -> dict[str, str]:
    return {name: hashlib.sha256((source / name).read_bytes()).hexdigest() for name in paths}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-config", type=Path, default=ROOT / ".run/owner-daemon/native-accessibility.cargo.toml")
    parser.add_argument("--cache-root", type=Path, default=ROOT / ".run/owner-daemon")
    parser.add_argument("--source", help="Optional local git source, still verified against the exact pin")
    args = parser.parse_args()
    patch = PATCH.read_text()
    digest = hashlib.sha256(patch.encode()).hexdigest()
    paths = patched_files(patch)
    if not paths or any(Path(p).is_absolute() or ".." in Path(p).parts for p in paths):
        raise RuntimeError("Invalid Makepad patch paths")
    cache = args.cache_root.resolve()
    cache.mkdir(parents=True, exist_ok=True)
    source = cache / f"makepad-ax-{PIN[:8]}-{digest[:12]}"
    manifest = cache / f"{source.name}.json"
    if source.exists():
        if not manifest.exists():
            raise RuntimeError(f"Unverified existing checkout: {source}; use a different --cache-root")
        previous = json.loads(manifest.read_text())
        if previous.get("pin") != PIN or previous.get("patchSha256") != digest:
            raise RuntimeError("Prepared source manifest mismatch")
        if run(["git", "rev-parse", "HEAD"], source) != PIN:
            raise RuntimeError("Prepared source HEAD changed")
        if fingerprints(source, paths) != previous.get("files"):
            raise RuntimeError("Prepared patch was locally edited; refusing to overwrite it")
        changed = run(["git", "status", "--porcelain", "--untracked-files=all"], source)
        unexpected = [line[3:] for line in changed.splitlines() if line[3:] not in paths and line[3:] != "Cargo.lock"]
        if unexpected:
            raise RuntimeError(f"Unexpected source changes: {unexpected}")
    else:
        local = args.source
        if local is None:
            candidates = sorted((Path.home() / ".cargo/git/checkouts").glob("makepad-*/*"))
            for candidate in candidates:
                if (candidate / ".git").exists():
                    try:
                        if run(["git", "rev-parse", "HEAD"], candidate) == PIN:
                            local = str(candidate)
                            break
                    except subprocess.CalledProcessError:
                        pass
        run(["git", "clone", "--no-checkout", local or SOURCE, str(source)])
        if run(["git", "rev-parse", f"{PIN}^{{commit}}"], source) != PIN:
            raise RuntimeError("Pinned Makepad commit unavailable")
        run(["git", "checkout", "--detach", PIN], source)
        run(["git", "apply", "--check", str(PATCH)], source)
        run(["git", "apply", str(PATCH)], source)
        manifest.write_text(json.dumps({"pin": PIN, "patchSha256": digest, "files": fingerprints(source, paths)}, indent=2) + "\n")
    metadata = json.loads(run(["cargo", "metadata", "--no-deps", "--format-version", "1"], source))
    members = set(metadata["workspace_members"])
    packages = {p["name"]: str(Path(p["manifest_path"]).parent) for p in metadata["packages"] if p["id"] in members}
    config = "# Generated by tools/prepare-owner-accessibility.py; do not edit.\n"
    config += f"# Makepad {PIN}; patch SHA-256 {digest}\n"
    source_packages = {SOURCE: set(packages)}
    # Cargo patches are not transitive: Desktop aliases several historical
    # Makepad sources to this pin. Patch each alias directly to the same paths.
    current = None
    for line in (ROOT / "Cargo.toml").read_text().splitlines():
        if line.startswith("["):
            match = re.fullmatch(r'\[patch\."([^\"]+)"\]', line)
            current = match[1] if match and "makepad" in match[1].lower() else None
        elif current:
            match = re.match(r"([A-Za-z0-9_-]+)\s*=", line)
            if match and match[1] in packages:
                source_packages.setdefault(current, set()).add(match[1])
    for url, names in sorted(source_packages.items()):
        config += f"\n[patch.{json.dumps(url)}]\n"
        for name in sorted(names):
            config += f"{json.dumps(name)} = {{ path = {json.dumps(packages[name])} }}\n"
    args.output_config.parent.mkdir(parents=True, exist_ok=True)
    args.output_config.write_text(config)
    print(json.dumps({"config": str(args.output_config.resolve()), "source": str(source), "pin": PIN,
                      "patchSha256": digest, "packages": len(packages)}))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", None)
        print(f"prepare-owner-accessibility: {error}\n{detail or ''}", file=sys.stderr)
        sys.exit(1)
